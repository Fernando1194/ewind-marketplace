// A pontuação final (. : *) é tratada à parte em translatePt e devolvida como estava no original,
// então as chaves e os valores ficam sem ela.
const TAIL = /[\s.:*…]+$/
const T: Record<string, string> = {}
for (const k of Object.keys(D)) T[k.replace(TAIL, '') || k] = D[k].replace(TAIL, '') || D[k]

const MONTHS_FULL = ['janeiro','fevereiro','março','abril','maio','junho','julho','agosto','setembro','outubro','novembro','dezembro']
const MONTHS_EN = ['January','February','March','April','May','June','July','August','September','October','November','December']

// Textos montados com variáveis (um único nó de texto na tela).
const RULES: Array<[RegExp, (m: RegExpMatchArray) => string]> = [
  [/^há (\d+)h$/i, m => `${m[1]}h ago`],
  [/^há (\d+) dia\(s\)$/i, m => `${m[1]} day(s) ago`],
  [/^Em andamento \((\d+)\)$/i, m => `In progress (${m[1]})`],
  [/^Encerrados \((\d+)\)$/i, m => `Closed (${m[1]})`],
  [/^Orçamentos \((\d+)\)$/i, m => `Quotes (${m[1]})`],
  [/^Orçamento \((.+)$/i, m => `Budget (${m[1]}`],
  [/^(\d+)\/(\d+) parcelas$/i, m => `${m[1]}/${m[2]} installments`],
  [/^pago em (.+)$/i, m => `paid on ${m[1]}`],
  [/^Vence (.+)$/i, m => `Due ${m[1]}`],
  [/^(\d+) convidados$/i, m => `${m[1]} guests`],
  [/^(\d+) dias úteis$/i, m => `${m[1]} business days`],
  [/^Publicando\.\.\. (\d+)%$/i, m => `Publishing... ${m[1]}%`],
  [/^\(?confiança: (.+?)\)?$/i, m => `(confidence: ${m[1]})`],
  [/^sua proposta de R\$ (.+)$/i, m => `your proposal of R$ ${m[1]}`],
  [/^(\d{1,2}) de ([a-zç]+) de (\d{4})$/i, m => {
    const i = MONTHS_FULL.indexOf(m[2].toLowerCase()); return i < 0 ? m[0] : `${MONTHS_EN[i]} ${m[1]}, ${m[3]}`
  }],
  [/^(\d{2}) (JAN|FEV|MAR|ABR|MAI|JUN|JUL|AGO|SET|OUT|NOV|DEZ)$/, m => `${m[1]} ${T[m[2].toLowerCase()] ?? m[2]}`],
  [/^Olá! Temos disponibilidade para (.+?) em (.+?)\. Ficamos felizes em receber (.+?) convidados por (.+?)h\.\.\.$/i,
    m => `Hello! We are available for ${m[1]} on ${m[2]}. We would be happy to host ${m[3]} guests for ${m[4]}h...`],
  [/^(\d+) arquivo\(s\) selecionado\(s\)$/i, m => `${m[1]} file(s) selected`],
  [/^Não alocados \((\d+)\)?$/i, m => `Unassigned (${m[1]})`],
]

const LETTER = /[\p{L}\p{N}]/u

function lookup(core: string): string | null {
  const key = core.toLowerCase()
  let out: string | undefined = T[key]
  if (out === undefined) {
    for (const [re, fn] of RULES) { const m = core.match(re); if (m) { out = fn(m); break } }
  }
  if (out === undefined) return null
  // texto todo em maiúsculas no original continua em maiúsculas
  if (core.length > 2 && core === core.toUpperCase() && core !== core.toLowerCase()) return out.toUpperCase()
  return out
}

/** Traduz um trecho de texto; devolve o próprio texto se não houver tradução. */
export function translatePt(text: string): string {
  const lead = text.match(/^\s*/)![0], trail = text.match(/\s*$/)![0]
  const body = text.trim().replace(/\s+/g, ' ')
  if (!body || !LETTER.test(body)) return text
  let r = lookup(body)
  if (r !== null) return lead + r + trail
  const bare = body.replace(TAIL, '')
  if (bare && bare !== body) {
    r = lookup(bare)
    if (r !== null) return lead + r + body.slice(bare.length) + trail
  }
  // tira símbolos/emoji no começo e pontuação solta no fim (mantém ! ? e ")") e tenta de novo
  const m = body.match(/^((?:[^\p{L}\p{N}]|ℹ)*)(.*?)([^\p{L}\p{N}!?)]*)$/su)
  if (m && m[2]) {
    r = lookup(m[2])
    if (r !== null) return lead + m[1] + r + m[3] + trail
  }
  return text
}
